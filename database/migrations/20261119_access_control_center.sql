-- Central de Controle de Acesso ANIT
-- Migration idempotente. Não altera nem exclui registros institucionais existentes.

CREATE TABLE IF NOT EXISTS anit.user_permissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES anit.user_profiles(user_id) ON DELETE CASCADE,
  permission_key text NOT NULL,
  allowed boolean NOT NULL DEFAULT true,
  granted_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT user_permissions_user_permission_key UNIQUE (user_id, permission_key)
);

ALTER TABLE anit.user_permissions ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION anit.has_permission(p_permission_key text)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = anit, public
AS $$
DECLARE
  v_user uuid := auth.uid();
  v_role text;
  v_override boolean;
  v_role_allowed boolean;
BEGIN
  IF v_user IS NULL THEN RETURN false; END IF;
  SELECT role INTO v_role FROM anit.user_profiles
   WHERE user_id = v_user AND active = true;
  IF v_role IS NULL THEN RETURN false; END IF;
  IF v_role IN ('president','vice_president','administrator') THEN RETURN true; END IF;

  SELECT allowed INTO v_override FROM anit.user_permissions
   WHERE user_id = v_user AND permission_key = p_permission_key;
  IF FOUND THEN RETURN v_override; END IF;

  SELECT allowed INTO v_role_allowed FROM anit.role_permissions
   WHERE role = v_role AND permission_key = p_permission_key;
  RETURN COALESCE(v_role_allowed, false);
END;
$$;

CREATE OR REPLACE FUNCTION anit.current_permissions()
RETURNS text[]
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = anit, public
AS $$
  SELECT COALESCE(array_agg(permission_key ORDER BY permission_key), ARRAY[]::text[])
  FROM (
    SELECT rp.permission_key, rp.allowed
      FROM anit.role_permissions rp
      JOIN anit.user_profiles up ON up.role = rp.role
     WHERE up.user_id = auth.uid() AND up.active = true
    UNION
    SELECT permission_key, allowed
      FROM anit.user_permissions
     WHERE user_id = auth.uid()
  ) p
  WHERE p.allowed = true
    AND NOT EXISTS (
      SELECT 1 FROM anit.user_permissions u
       WHERE u.user_id = auth.uid() AND u.permission_key = p.permission_key
         AND u.allowed = false
    );
$$;

CREATE OR REPLACE FUNCTION anit.set_user_permission(
  p_user_id uuid, p_permission_key text, p_allowed boolean
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = anit, public
AS $$
DECLARE
  v_actor_role text;
  v_scope text;
BEGIN
  SELECT role INTO v_actor_role FROM anit.user_profiles
   WHERE user_id = auth.uid() AND active = true;
  IF v_actor_role IS NULL THEN RAISE EXCEPTION 'Perfil institucional ativo não encontrado.'; END IF;
  IF NOT EXISTS (SELECT 1 FROM anit.user_profiles WHERE user_id = p_user_id AND active = true) THEN
    RAISE EXCEPTION 'O usuário de destino não possui perfil institucional ativo.';
  END IF;

  IF v_actor_role IN ('president','vice_president','administrator') THEN
    NULL;
  ELSIF v_actor_role = 'treasurer' AND p_permission_key LIKE 'finance.%' THEN
    NULL;
  ELSIF v_actor_role = 'secretary' AND p_permission_key LIKE ANY (ARRAY[
    'associates.%','demands.%','documents.%','protocols.%','meetings.%','communications.%'
  ]) THEN
    NULL;
  ELSE
    RAISE EXCEPTION 'Seu perfil não pode administrar a permissão solicitada.';
  END IF;

  INSERT INTO anit.user_permissions(user_id, permission_key, allowed, granted_by, updated_at)
  VALUES (p_user_id, p_permission_key, p_allowed, auth.uid(), now())
  ON CONFLICT (user_id, permission_key)
  DO UPDATE SET allowed = EXCLUDED.allowed, granted_by = EXCLUDED.granted_by, updated_at = now();
END;
$$;

CREATE OR REPLACE FUNCTION anit.update_own_profile(p_full_name text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = anit, public
AS $$
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Sessão não autenticada.'; END IF;
  IF length(trim(COALESCE(p_full_name,''))) < 3 THEN
    RAISE EXCEPTION 'Informe um nome completo válido.';
  END IF;
  UPDATE anit.user_profiles
     SET full_name = trim(p_full_name), updated_at = now()
   WHERE user_id = auth.uid() AND active = true;
  IF NOT FOUND THEN RAISE EXCEPTION 'Perfil institucional ativo não encontrado.'; END IF;
END;
$$;

