-- Leitura e gestão passam a consultar a permissão efetiva no banco.
DO $$
DECLARE r record;
BEGIN
  FOR r IN SELECT * FROM (VALUES
    ('associates','associates'),('board_members','board'),
    ('financial_entries','finance'),('protocols','protocols'),
    ('official_documents','documents'),('legal_cases','legal'),
    ('legal_references','legal'),('institutional_relations','institutional'),
    ('meetings','meetings'),('meeting_attendees','meetings'),
    ('meeting_action_items','meetings'),('meeting_attachments','meetings'),
    ('meeting_updates','meetings'),('communications','communications'),
    ('member_demands','demands')
  ) AS x(table_name, permission_prefix)
  LOOP
    EXECUTE format('DROP POLICY IF EXISTS %I ON anit.%I', r.permission_prefix || '_read', r.table_name);
    EXECUTE format('DROP POLICY IF EXISTS %I ON anit.%I', r.permission_prefix || '_manage', r.table_name);
    EXECUTE format('DROP POLICY IF EXISTS %I ON anit.%I', r.table_name || '_read', r.table_name);
    EXECUTE format('DROP POLICY IF EXISTS %I ON anit.%I', r.table_name || '_manage', r.table_name);
    EXECUTE format('CREATE POLICY %I ON anit.%I FOR SELECT TO authenticated USING (anit.has_permission(%L))',
      r.table_name || '_read', r.table_name, r.permission_prefix || '.read');
    EXECUTE format('CREATE POLICY %I ON anit.%I FOR ALL TO authenticated USING (anit.has_permission(%L)) WITH CHECK (anit.has_permission(%L))',
      r.table_name || '_manage', r.table_name, r.permission_prefix || '.manage', r.permission_prefix || '.manage');
  END LOOP;
END $$;

